const FONT_CHARS = Object.keys(FONT_COLS);        // atlas order
const FONT_INDEX = {};                            // char -> atlas slot
for (let i = 0; i < FONT_CHARS.length; i++) FONT_INDEX[FONT_CHARS[i]] = i;
const FONT_W = 5;                                 // glyph width
const FONT_H = 8;                                 // glyph height
const FONT_ADV = 6;                               // advance incl. 1px gap
const FONT_SHADOW = '#050705';                    // drop shadow color
const fontAtlases = {};                           // color -> atlas canvas
let fontAtlasCount = 0;                           // cache size

// atlas of every glyph in one color, built on demand
function fontAtlas(color) {
  let a = fontAtlases[color];
  if (a) return a;
  if (fontAtlasCount > 64) {                      // ponytail: crude cap, LRU if colors churn
    for (const k in fontAtlases) delete fontAtlases[k];
    fontAtlasCount = 0;
  }
  a = makeCanvas(FONT_CHARS.length * FONT_ADV, FONT_H);
  const g = a.getContext('2d');
  g.fillStyle = color;
  for (let i = 0; i < FONT_CHARS.length; i++) {
    const cols = FONT_COLS[FONT_CHARS[i]];
    for (let cx = 0; cx < FONT_W; cx++) {
      for (let cy = 0; cy < FONT_H; cy++) {
        if (cols[cx] & (1 << cy)) g.fillRect(i * FONT_ADV + cx, cy, 1, 1);
      }
    }
  }
  fontAtlases[color] = a;
  fontAtlasCount += 1;
  return a;
}

// atlas slot for a char (unknown -> '?')
function glyphSlot(ch) {
  const i = FONT_INDEX[ch];
  if (i === undefined) return FONT_INDEX['?'];
  return i;
}

// width in pixels of a string at integer scale
function measurePixelText(s, scale) {
  const n = String(s).length;
  if (n === 0) return 0;
  return (n * FONT_ADV - 1) * scale;
}

// draw one glyph at top-left x,y
function drawGlyph(g, atlas, ch, x, y, scale) {
  const sx = glyphSlot(ch) * FONT_ADV;
  g.drawImage(atlas, sx, 0, FONT_W, FONT_H, x, y, FONT_W * scale, FONT_H * scale);
}

// pixel text, y = top of the glyph cell, no shadow
function drawPixelText(g, s, x, y, scale, color, align) {
  const str = String(s);
  const sc2 = Math.max(1, Math.round(scale || 1));
  const atlas = fontAtlas(color || '#a8b5a0');
  let left = x;
  if (align === 'center') left = x - measurePixelText(str, sc2) / 2;
  if (align === 'right') left = x - measurePixelText(str, sc2);
  left = Math.round(left);
  const top = Math.round(y);
  const prev = g.imageSmoothingEnabled;           // keep pixels hard
  g.imageSmoothingEnabled = false;
  for (let i = 0; i < str.length; i++) {
    if (str[i] === ' ') continue;
    drawGlyph(g, atlas, str[i], left + i * FONT_ADV * sc2, top, sc2);
  }
  g.imageSmoothingEnabled = prev;
}

// size (approx px height) -> integer scale
function fontScale(size) {
  return Math.max(2, Math.round(size / 8));       // never below 2: scale 1 is unreadable
}

// v1-compatible label: y is the vertical middle, 1px-per-scale drop shadow
function label(g, s, x, y, size, color, align, style) {
  const k = fontScale(size);
  const top = y - Math.round(3.5 * k);            // center caps on y
  const al = align || 'center';
  drawPixelText(g, s, x + k, top + k, k, FONT_SHADOW, al);
  drawPixelText(g, s, x, top, k, color, al);
}

// title text: per-glyph jitter with faint blood / cold offsets
function shakyText(g, s, x, y, size, color) {
  const str = String(s);
  const k = fontScale(size);
  const left = Math.round(x - measurePixelText(str, k) / 2);
  const top = Math.round(y - 3.5 * k);
  const red = fontAtlas('rgba(138,15,18,0.7)');
  const cold = fontAtlas('rgba(90,130,120,0.3)');
  const shade = fontAtlas(FONT_SHADOW);
  const main = fontAtlas(color);
  const prev = g.imageSmoothingEnabled;
  g.imageSmoothingEnabled = false;
  for (let i = 0; i < str.length; i++) {
    const ch = str[i];
    if (ch === ' ') continue;
    let jx = Math.round(rand(-0.6, 0.6)) * Math.max(1, k >> 2);  // small jitter
    let jy = Math.round(rand(-0.6, 0.6)) * Math.max(1, k >> 2);
    if (Math.random() < 0.03) {                   // rare twitch
      jx = jx * 4;
      jy = jy * 4;
    }
    const gx = left + i * FONT_ADV * k + jx;
    const gy = top + jy;
    drawGlyph(g, shade, ch, gx + k, gy + k, k);   // drop shadow
    drawGlyph(g, red, ch, gx + k, gy, k);         // blood offset
    drawGlyph(g, cold, ch, gx - k, gy, k);        // cold offset
    drawGlyph(g, main, ch, gx, gy, k);            // letter
  }
  g.imageSmoothingEnabled = prev;
}
